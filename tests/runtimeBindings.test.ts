import { describe, expect, it } from "vitest";
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

const directory = join(__dirname, "..", "src", "generated", "bindings");
const binding = (name: string) => readFileSync(join(directory, `${name}.ts`), "utf8");

describe("native runtime bindings", () => {
  const expected = [
    "AgentKind",
    "Connection",
    "ConnectionHealth",
    "ConnectionHealthStatus",
    "ConnectionModel",
    "ConnectionSummary",
    "ConnectionValidation",
    "DiscoverySource",
    "Provider",
    "RuntimeKind",
    "RuntimeRef",
    "UnresolvedReason",
    "Workspace",
    "WorkspaceAvailability",
  ];

  it("contains only native persistence and runtime references", () => {
    const present = readdirSync(directory)
      .filter((file) => file.endsWith(".ts"))
      .map((file) => file.replace(/\.ts$/, ""))
      .sort();
    expect(present).toEqual(expected.sort());
  });

  it("keeps generated files generated", () => {
    for (const name of expected) {
      expect(binding(name), name).toContain("Do not edit this file manually");
    }
  });

  it("never exposes connection credentials", () => {
    const source = binding("Connection");
    expect(source).toContain("secret_ref: string | null");
    expect(source).not.toMatch(/\b(api_key|password|token)\b/i);
  });

  it("keeps chat and local-agent runtime references", () => {
    const source = binding("RuntimeRef");
    expect(source).toContain('"kind": "chat-model"');
    expect(source).toContain('"kind": "coding-agent"');
    expect(source).toContain("agent_session_id?: string | null");
  });
});
